#!/usr/bin/env python3
"""Generate the HTML5 named character reference table.

CommonMark requires the entity names of the HTML5 specification, which is the
table Python ships as `html.entities.html5`. Only the forms that end in a
semicolon are valid in CommonMark, so the legacy forms without one are dropped
(2125 names remain for Unicode 15.1).

    python3 scripts/gen_entity.py

The output is a sorted pair of parallel arrays, which the parser binary-searches
so that no table is built at start-up.
"""

from __future__ import annotations

import html.entities
import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "entity_table.mbt"


def moonbit_string(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main() -> int:
    names = sorted(name[:-1] for name in html.entities.html5 if name.endswith(";"))
    lines = [
        "// Generated by scripts/gen_entity.py from Python's html.entities.html5",
        f"// (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "///|",
        "/// The names of the HTML5 named character references, without the `&` and",
        "/// the `;`, in ascending order.",
        f"let entity_names : Array[String] = [",
    ]
    for name in names:
        lines.append(f"  {moonbit_string(name)},")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// The text each name in `entity_names` stands for, at the same index.")
    lines.append("let entity_values : Array[String] = [")
    for name in names:
        lines.append(f"  {moonbit_string(html.entities.html5[name + ';'])},")
    lines.append("]")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(names)} named references -> {OUT.relative_to(OUT.parent.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
