#!/usr/bin/env python3
"""Generate the Unicode tables the parser needs.

CommonMark classifies the characters next to a delimiter run as whitespace or
punctuation, and folds case when it compares link labels. Both need Unicode
data, so the tables are generated here from Python's `unicodedata` and committed
as source; the library itself has no start-up cost and no dependency.

    python3 scripts/gen_unicode.py

* `punctuation` holds the code point ranges of the P and S general categories.
* `fold` maps every code point whose full case folding differs from itself,
  which is what the specification prescribes for link labels.
* `whitespace` is the much smaller Unicode White_Space property, written by hand
  below because `unicodedata` does not expose properties.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "unicode_table.mbt"

WHITESPACE = [
    0x0009,
    0x000A,
    0x000B,
    0x000C,
    0x000D,
    0x0020,
    0x0085,
    0x00A0,
    0x1680,
    0x2000,
    0x2001,
    0x2002,
    0x2003,
    0x2004,
    0x2005,
    0x2006,
    0x2007,
    0x2008,
    0x2009,
    0x200A,
    0x2028,
    0x2029,
    0x202F,
    0x205F,
    0x3000,
]


def moonbit_string(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 0x20:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main() -> int:
    ranges: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if unicodedata.category(chr(cp))[0] in ("P", "S"):
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1] = (ranges[-1][0], cp)
            else:
                ranges.append((cp, cp))

    narrow: list[tuple[int, int]] = []
    for cp in range(0x110000):
        if unicodedata.category(chr(cp))[0] == "P":
            if narrow and narrow[-1][1] == cp - 1:
                narrow[-1] = (narrow[-1][0], cp)
            else:
                narrow.append((cp, cp))

    folds = []
    for cp in range(0x110000):
        folded = chr(cp).casefold()
        if folded != chr(cp):
            folds.append((cp, folded))

    lines = [
        "// Generated by scripts/gen_unicode.py from Python's unicodedata",
        f"// (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "///|",
        "/// The code points of the Unicode White_Space property, ascending.",
        "let whitespace_code_points : Array[Int] = [",
    ]
    for cp in WHITESPACE:
        lines.append(f"  0x{cp:04X},")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// Start and end of each run of P (punctuation) or S (symbol) code")
    lines.append("/// points, ascending and inclusive on both ends.")
    lines.append("let punctuation_ranges : Array[Int] = [")
    for start, end in ranges:
        lines.append(f"  0x{start:04X}, 0x{end:04X},")
    lines.append("]")
    lines.append("")
    lines.append("")
    lines.append("///|")
    lines.append("/// Start and end of each run of P (punctuation) code points, without the")
    lines.append("/// S (symbol) ones, ascending and inclusive on both ends.")
    lines.append("let punctuation_only_ranges : Array[Int] = [")
    for start, end in narrow:
        lines.append(f"  0x{start:04X}, 0x{end:04X},")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// Code points whose full case folding differs from the character")
    lines.append("/// itself, ascending.")
    lines.append("let fold_from : Array[Int] = [")
    for cp, _ in folds:
        lines.append(f"  0x{cp:04X},")
    lines.append("]")
    lines.append("")
    lines.append("///|")
    lines.append("/// What each code point in `fold_from` folds to, at the same index.")
    lines.append("let fold_to : Array[String] = [")
    for _, folded in folds:
        lines.append(f"  {moonbit_string(folded)},")
    lines.append("]")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        f"{len(ranges)} punctuation ranges, {len(narrow)} punctuation-only ranges, "
        f"{len(folds)} case folding entries -> {OUT.name}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
