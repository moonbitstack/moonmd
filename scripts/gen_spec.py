#!/usr/bin/env python3
"""Generate the CommonMark and GFM conformance data compiled by the test suite.

Two pinned corpora are read from `.ref/` (a checkout beside this repository) and
written out as MoonBit source under `src/tests/spec/`:

    CommonMark 0.31.2   https://spec.commonmark.org/0.31.2/spec.json
    cmark-gfm           test/extensions.txt   (pinned by commit, see PIN below)

Both files are downloaded once; the generated `.mbt` files are what the test
suite compiles, so CI needs neither network access nor a C toolchain.

    python3 scripts/gen_spec.py

The example numbers are the ones the corpora use, so a failure report refers to
the same example number the upstream documentation uses.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / ".ref"
SPEC_JSON = REF / "spec-0.31.2.json"
EXTENSIONS_TXT = REF / "cmark-gfm" / "test" / "extensions.txt"
OUT_DIR = ROOT / "src" / "tests" / "spec"

CASES_PER_PART = 40

# Examples cmark-gfm marks as "must not crash" rather than "must produce this".
IGNORE_MARKER = "<IGNORE>"


def moonbit_string(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            raise SystemExit(f"unexpected control character {ord(ch):#x} in {text!r}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def emit(path: Path, source: str, doc: str, cases: list[dict], function: str) -> None:
    lines = [
        "// Generated by scripts/gen_spec.py from " + source + ".",
        "// Do not edit: change the script and regenerate.",
        "",
        "///|",
        "/// " + doc,
        "pub fn " + function + "() -> Array[Case] {",
        "  let all : Array[Case] = []",
    ]
    parts = [
        cases[i : i + CASES_PER_PART] for i in range(0, len(cases), CASES_PER_PART)
    ]
    for index, part in enumerate(parts):
        lines.append(f"  all.append({function}_part_{index:02d}()[:])")
    lines.append("  all")
    lines.append("}")
    lines.append("")
    for index, part in enumerate(parts):
        lines.append("///|")
        lines.append(f"fn {function}_part_{index:02d}() -> Array[Case] {{")
        lines.append("  [")
        for case in part:
            lines.append(
                "    Case::{ example: %d, section: %s, markdown: %s, html: %s },"
                % (
                    case["example"],
                    moonbit_string(case["section"]),
                    moonbit_string(case["markdown"]),
                    moonbit_string(case["html"]),
                )
            )
        lines.append("  ]")
        lines.append("}")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def commonmark_cases() -> list[dict]:
    if not SPEC_JSON.is_file():
        raise SystemExit(
            f"{SPEC_JSON} is missing; fetch https://spec.commonmark.org/0.31.2/spec.json"
        )
    raw = json.loads(SPEC_JSON.read_text(encoding="utf-8"))
    return [
        {
            "example": item["example"],
            "section": item["section"],
            "markdown": item["markdown"].replace("\r\n", "\n"),
            "html": item["html"].replace("\r\n", "\n"),
        }
        for item in raw
    ]


EXAMPLE_OPEN = re.compile(r"^`{32} example(?: (.*))?$")


def extensions_cases() -> list[dict]:
    if not EXTENSIONS_TXT.is_file():
        raise SystemExit(f"{EXTENSIONS_TXT} is missing; clone github/cmark-gfm")
    cases: list[dict] = []
    section = ""
    number = 0
    state = "text"
    markdown: list[str] = []
    html: list[str] = []
    for line in EXTENSIONS_TXT.read_text(encoding="utf-8").splitlines():
        if state == "text":
            if line.startswith("#"):
                section = line.lstrip("#").strip()
            elif EXAMPLE_OPEN.match(line):
                number += 1
                markdown, html, state = [], [], "markdown"
        elif state == "markdown":
            if line == ".":
                state = "html"
            else:
                markdown.append(line)
        else:
            if line.startswith("`" * 32):
                cases.append(
                    {
                        "example": number,
                        "section": section,
                        "markdown": "\n".join(markdown) + "\n",
                        "html": "\n".join(html) + "\n",
                    }
                )
                state = "text"
            else:
                html.append(line)
    return cases


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    commonmark = commonmark_cases()
    extensions = extensions_cases()
    emit(
        OUT_DIR / "commonmark_suite.mbt",
        "CommonMark 0.31.2 spec.json",
        "The CommonMark 0.31.2 specification examples, in specification order.",
        commonmark,
        "commonmark_cases",
    )
    emit(
        OUT_DIR / "gfm_suite.mbt",
        "cmark-gfm test/extensions.txt",
        "The example blocks of the GitHub Flavored Markdown extension corpus.",
        extensions,
        "gfm_cases",
    )
    ignored = sum(1 for case in extensions if case["html"].strip() == IGNORE_MARKER)
    print(
        f"{len(commonmark)} CommonMark examples, {len(extensions)} extension examples "
        f"({ignored} of them crash-only)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
